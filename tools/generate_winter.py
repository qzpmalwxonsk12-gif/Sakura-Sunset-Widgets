"""Offline 320x180 winter painting with falling snow that dissolves into the ground."""
from functools import lru_cache
import hashlib
import json
import math
import random
from pathlib import Path
from PIL import Image, ImageDraw
from generate_assets import bitmap_xml

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT/'app/src/main/res'
W,H,N = 320,180,96
LAND_AT, MERGED_AT = .83,.98
SNOW_COLORS = [(247,250,255),(224,236,255),(200,218,245),(176,199,231)]


def snow_specs():
    rng=random.Random(261027)
    return [dict(land_x=rng.uniform(16,W-16),land_y=rng.uniform(150,H-4),
                 drift=rng.uniform(5,23),amplitude=rng.uniform(1,3.5),
                 phase=(i*N/80+rng.uniform(-.35,.35))%N,
                 size=2 if i%5==0 else 1,color=i%4,waves=rng.choice([1,2]))
            for i in range(80)]


def state(p, frame):
    t=((frame+p['phase'])%N)/N
    q=min(t/LAND_AT,1)
    x=p['land_x']-p['drift']*(1-q)
    x+=p['amplitude']*math.sin(math.tau*q*p['waves'])*math.sin(math.pi*q)
    y=-5+(p['land_y']+5)*q
    merge=max(0,min(1,(t-LAND_AT)/(MERGED_AT-LAND_AT)))
    # Smoothstep brings the snowfall to its resting local snow color, then disappears.
    alpha=1-merge*merge*(3-2*merge)
    return x,y,alpha,merge


@lru_cache(maxsize=16384)
def nearest_color(rgb, palette):
    return min(palette,key=lambda c:sum((a-b)**2 for a,b in zip(c,rgb)))


def palette_for(base):
    return tuple(sorted(set(base.get_flattened_data())|set(SNOW_COLORS)))


def render(base, frame):
    im=base.convert('RGBA'); draw=ImageDraw.Draw(im); palette=palette_for(base)
    for p in snow_specs():
        fx,fy,alpha,merge=state(p,frame)
        if alpha<=0: continue
        x,y=round(fx),round(fy)
        pixels=[(x,y)]
        if p['size']==2 and merge<.45: pixels += [(x+1,y)]
        for px,py in pixels:
            if not (0<=px<W and 0<=py<H): continue
            ground=base.getpixel((px,py))
            mixed=tuple(round(s*alpha+g*(1-alpha)) for s,g in zip(SNOW_COLORS[p['color']],ground))
            draw.point((px,py), fill=nearest_color(mixed,palette))
    mask=Image.new('L',(W,H)); ImageDraw.Draw(mask).rounded_rectangle((0,0,W-1,H-1),radius=5,fill=255)
    im.putalpha(mask)
    return im


def main():
    source=Image.open(ROOT/'art/source/winter-cabin.png').convert('RGB')
    small=source.resize((W,H),Image.Resampling.NEAREST)
    base=small.quantize(colors=96,dither=Image.Dither.NONE).convert('RGB')
    # Tiny amber windows are easily lost when a snow-dominated palette is reduced.
    # Protect the source's warm pixels with their own small palette, without repainting.
    def warm(c): return c[0]>c[2]*1.3 and c[0]>c[1]*1.1
    warm_pixels=[c for c in small.get_flattened_data() if warm(c)]
    swatch=Image.new('RGB',(len(warm_pixels),1)); swatch.putdata(warm_pixels)
    warm_palette=tuple(sorted(set(swatch.quantize(colors=16,dither=Image.Dither.NONE).convert('RGB').get_flattened_data())))
    for y in range(H):
        for x in range(W):
            color=small.getpixel((x,y))
            if warm(color): base.putpixel((x,y),nearest_color(color,warm_palette))
    base.save(ROOT/'art/winter-base.png')
    colors=palette_for(base); lookup={c:i for i,c in enumerate(colors)}
    frames=[]; hashes=[]
    for i in range(N):
        im=render(base,i); frames.append(im)
        indexed=Image.frombytes('P',im.size,bytes(lookup[(r,g,b)] if a else 255 for r,g,b,a in im.get_flattened_data()))
        indexed.putpalette([v for c in colors for v in c]+[0]*(768-len(colors)*3)); indexed.info['transparency']=255
        name=f'winter_frame_{i:03d}'
        path=RES/f'drawable-nodpi/{name}_pixels.png'; indexed.save(path,optimize=True)
        hashes.append(hashlib.sha256(path.read_bytes()).hexdigest())
        (RES/f'drawable/{name}.xml').write_text(bitmap_xml(name+'_pixels'),encoding='utf-8')
    (RES/'drawable/winter_preview.xml').write_text(bitmap_xml('winter_frame_000_pixels'),encoding='utf-8')
    (ROOT/'app/src/main/java/com/sakurasunset/widget/WinterFrames.kt').write_text(
        'package com.sakurasunset.widget\n\n// Generated by tools/generate_winter.py\nobject WinterFrames {\n    val resources = intArrayOf(\n'+
        ''.join(f'        R.drawable.winter_frame_{i:03d},\n' for i in range(N))+'    )\n}\n',encoding='utf-8')
    frames[0].resize((960,540),Image.Resampling.NEAREST).save(ROOT/'art/previews/winter-painting.png')
    preview=[im.resize((640,360),Image.Resampling.NEAREST) for im in frames]
    preview[0].save(ROOT/'art/previews/winter-loop.gif',save_all=True,append_images=preview[1:],duration=[120,130]*48,loop=0,disposal=2,optimize=True)
    metrics=dict(canvas=[W,H],frames=N,fps=8,loop_ms=12000,snowflakes=80,
                 ground_contact_phase=LAND_AT,fully_merged_phase=MERGED_AT,
                 png_bytes=sum(p.stat().st_size for p in (RES/'drawable-nodpi').glob('winter_frame*png')),
                 all_frames_decoded_upper_bound_bytes=W*H*4*N,
                 source_sha256=hashlib.sha256((ROOT/'art/source/winter-cabin.png').read_bytes()).hexdigest(),
                 frame_sha256=hashes)
    (ROOT/'art/winter-manifest.json').write_text(json.dumps(metrics,indent=2)+'\n')
    print(json.dumps({k:v for k,v in metrics.items() if k!='frame_sha256'},indent=2))


if __name__=='__main__': main()
